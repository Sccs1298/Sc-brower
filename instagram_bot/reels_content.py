DEFAULT_CTA_SAY = "עקבו אחרינו לעוד תוכן כזה."


def H(text, say, emoji=None, tag=None):
    return {"type": "hook", "text": text, "say": say, "emoji": emoji, "tag": tag}


def T(title, say, kicker=None, body=None, emoji=None, tsize=None):
    d = {"type": "text", "title": title, "say": say, "kicker": kicker, "body": body, "emoji": emoji}
    if tsize:
        d["tsize"] = tsize
    return d


def N(value, say, kicker=None, label=None, prefix="", suffix="", decimals=0, color="orange", sub=None, start=0):
    return {"type": "number", "value": value, "say": say, "kicker": kicker, "label": label, "prefix": prefix,
            "suffix": suffix, "decimals": decimals, "color": color, "sub": sub, "start": start}


def L(title, items, say):
    return {"type": "list", "title": title, "items": items, "say": say}


def C(say, trend="crash", title=None, value_label=None, caption=None, seed=7):
    return {"type": "chart", "trend": trend, "title": title, "value_label": value_label, "caption": caption, "say": say, "seed": seed}


