def full_caption(post):
    return f"{post['caption']}\n\n{DISCLAIMER}\n\n{' '.join(post['hashtags'])}"


def main():
    out_root = REPO_DIR / "first_posts"
    for post in POSTS:
        d = out_root / post["slug"]
        paths = render_carousel(post, d)
        (d / "caption.txt").write_text(full_caption(post), encoding="utf-8")
        print(f"{post['slug']}: {len(paths)} slides")


if __name__ == "__main__":
    main()
